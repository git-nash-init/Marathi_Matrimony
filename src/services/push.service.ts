import { supabase, isSupabaseConfigured } from '../lib/supabase';

/**
 * Web Push: registers /sw.js, subscribes this browser with the VAPID public key from Vault,
 * and stores the subscription (save_push_subscription RPC). The send-push Edge Function then
 * delivers every new notification row to the device, even when the site is closed.
 */

let active = false;

const urlBase64ToUint8Array = (base64: string): Uint8Array => {
  const padded = (base64 + '='.repeat((4 - (base64.length % 4)) % 4)).replace(/-/g, '+').replace(/_/g, '/');
  const raw = atob(padded);
  return Uint8Array.from(raw, (c) => c.charCodeAt(0));
};

async function getPublicKey(): Promise<string | null> {
  const { data } = await supabase.rpc('get_vapid_public_key');
  if (data) return data as string;
  // Keys are generated by the Edge Function on first use.
  const { data: init } = await supabase.functions.invoke('send-push', { body: { action: 'init' } });
  return (init as { public_key?: string } | null)?.public_key ?? null;
}

async function registration(): Promise<ServiceWorkerRegistration> {
  await navigator.serviceWorker.register('/sw.js');
  return navigator.serviceWorker.ready;
}

export const pushService = {
  isSupported(): boolean {
    return (
      typeof window !== 'undefined' &&
      'serviceWorker' in navigator &&
      'PushManager' in window &&
      'Notification' in window &&
      window.isSecureContext &&
      isSupabaseConfigured()
    );
  },

  /** True once this browser has a stored push subscription in this session. */
  isActive(): boolean {
    return active;
  },

  /**
   * Subscribes this browser for the signed-in user. Requires Notification permission 'granted'.
   * Safe to call repeatedly (re-saves the existing subscription, e.g. after switching accounts).
   */
  async enable(): Promise<boolean> {
    if (!this.isSupported() || Notification.permission !== 'granted') return false;
    try {
      const reg = await registration();
      let sub = await reg.pushManager.getSubscription();
      if (!sub) {
        const key = await getPublicKey();
        if (!key) return false;
        sub = await reg.pushManager.subscribe({
          userVisibleOnly: true,
          applicationServerKey: urlBase64ToUint8Array(key) as BufferSource,
        });
      }
      const json = sub.toJSON();
      const { error } = await supabase.rpc('save_push_subscription', {
        p_endpoint: sub.endpoint,
        p_p256dh: json.keys?.p256dh ?? '',
        p_auth: json.keys?.auth ?? '',
        p_user_agent: navigator.userAgent,
      });
      active = !error;
      if (error) console.warn('Could not save push subscription:', error.message);
      return active;
    } catch (err) {
      console.warn('Push subscription failed:', err);
      active = false;
      return false;
    }
  },

  /** Stops pushes to this browser (call before signing out, while the session is still valid). */
  async disable(): Promise<void> {
    active = false;
    if (!this.isSupported()) return;
    try {
      const reg = await navigator.serviceWorker.getRegistration('/sw.js');
      const sub = await reg?.pushManager.getSubscription();
      if (!sub) return;
      await supabase.rpc('delete_push_subscription', { p_endpoint: sub.endpoint });
      await sub.unsubscribe();
    } catch (err) {
      console.warn('Push unsubscribe failed:', err);
    }
  },
};
